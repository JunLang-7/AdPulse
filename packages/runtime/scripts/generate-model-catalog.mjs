// Generates packages/runtime/src/model-catalog.generated.json from the locked
// @earendil-works/pi-ai catalog. Run: node packages/runtime/scripts/generate-model-catalog.mjs
// The output is committed and guarded by tests/model-catalog.test.ts, which
// re-reads the SDK and fails when the two drift.
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { builtinProviders } from "@earendil-works/pi-ai/providers/all";
import { PI_AI_VERSION } from "@earendil-works/pi-ai";

const here = dirname(fileURLToPath(import.meta.url));
const output = join(here, "..", "src", "model-catalog.generated.ts");

// Only the fields AdPulse needs to (a) list a model and (b) rebuild an
// OpenAI Chat Completions route. Unknown pricing/capability stays as the SDK
// reports it; nothing is invented here.
const modelFields = ["id", "name", "api", "baseUrl", "provider", "reasoning", "input", "cost", "contextWindow", "maxTokens", "compat"];

function pickModel(model) {
	const picked = {};
	for (const field of modelFields) {
		if (model[field] !== undefined) picked[field] = model[field];
	}
	return picked;
}

// Ordered by how actionable the reason is: protocol/endpoint gaps come before
// the account-auth note, so e.g. OpenAI reads as a protocol gap rather than an
// OAuth one.
function reasonFor(provider, chatModels, protocols) {
	if (protocols.length === 0) return "目录中暂无对话模型。";
	if (!provider.baseUrl) return "需要账号、区域或部署名等额外参数，本期未接入。";
	if (chatModels.length === 0) return `该供应商使用 ${protocols.join(" / ")} 原生协议，尚未接通。`;
	if (provider.auth?.oauth) return "该供应商还依赖账号授权（OAuth），本期只支持个人 API Key 直连。";
	return "该供应商需要额外参数，本期未接入。";
}

const providers = builtinProviders().map((provider) => {
	const models = provider.getModels();
	const protocols = [...new Set(models.map((model) => model.api))];
	const chatModels = models.filter((model) => model.api === "openai-completions");
	const supported = chatModels.length > 0 && Boolean(provider.baseUrl) &&
		provider.baseUrl.startsWith("https://") && !provider.auth?.oauth;
	return {
		id: provider.id,
		name: provider.name,
		baseUrl: provider.baseUrl ?? null,
		supported,
		...(supported ? {} : { reason: reasonFor(provider, chatModels, protocols) }),
		// 认证方式只记录 SDK 声明，不从品牌名猜；云凭据类仍需看 reason。
		auth: {
			apiKey: Boolean(provider.auth?.apiKey),
			oauth: Boolean(provider.auth?.oauth),
		},
		protocols,
		models: supported ? chatModels.map(pickModel) : [],
	};
});

const document = {
	generatedFrom: { package: "@earendil-works/pi-ai", version: PI_AI_VERSION },
	providers,
};
const banner = [
	"// Generated by packages/runtime/scripts/generate-model-catalog.mjs from the locked",
	"// @earendil-works/pi-ai directory. Do not edit by hand; regenerate instead.",
];
writeFileSync(output, banner.join("\n") + "\nexport const modelCatalogDocument = " + JSON.stringify(document, null, "\t") + ";\n", "utf8");
const supported = providers.filter((provider) => provider.supported);
console.log(`wrote ${providers.length} providers (${supported.length} supported, ${supported.reduce((sum, item) => sum + item.models.length, 0)} models) to ${output}`);
